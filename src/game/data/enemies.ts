export const TIER_NAMES = ['', '', 'Hardened ', 'Mutated ', 'Feral ', 'Elite ', 'Apex '];

export function scaledStats(def: EnemyDef, tier: number) {
  if (def.boss) return { hp: def.hp, atk: def.atk, def: def.def, xp: def.xp, scrapMul: 1 };
  const t = Math.max(1, tier) - 1;
  return {
    hp: Math.round(def.hp * (1 + 0.5 * t)),
    atk: Math.round(def.atk * (1 + 0.25 * t) * 10) / 10,
    def: def.def + Math.floor(t / 2),
    xp: Math.round(def.xp * (1 + 0.35 * t)),
    scrapMul: 1 + 0.4 * t,
  };
}
